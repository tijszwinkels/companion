/**
 * Session applications: the shared descriptor and wire types.
 *
 * A session application replaces a conversation's default HTML chat with an
 * authored bundle from the widget library. It belongs to exactly one existing
 * AgentSessions conversation; applying one never creates another conversation
 * or starts a model turn. The backend (WidgetService and this module) owns its
 * code version, durable state, capabilities and event outbox.
 *
 * This file contains only types and constants, so browser/UI bundles can import
 * it without pulling in any service code. See README.md in this directory for
 * the HTTP view protocol and the agent tools.
 */

/**
 * How committed user edits reach the session's agent.
 *
 * - `immediate`: coalesced edits are queued as their own model turn behind any
 *   running or queued turn (the default).
 * - `next-input`: edits wait and are attached to the next message the person
 *   actually sends in this conversation.
 */
export type SessionApplicationEventMode = 'immediate' | 'next-input';

export const sessionApplicationEventModes: readonly SessionApplicationEventMode[] = [
  'immediate',
  'next-input',
];

/**
 * Delivery state of the application's user-edit events, for display only.
 *
 * `state` describes the newest batch:
 * - `idle`: nothing is waiting.
 * - `pending`: committed edits are recorded and not yet admitted to a model
 *   turn (debounce, waiting for next input, or a refused admission; see
 *   `failure`). Only such never-admitted edits can join a later batch.
 * - `queued`: a model turn carrying them is queued behind another turn.
 * - `delivering`: a model turn carrying them is running.
 * - `failed`: a turn carrying them failed, was stopped, or was interrupted by
 *   a restart. The agent may or may not have seen them. Failed batches are
 *   terminal: never replayed automatically and never folded into a new batch.
 *   They stay listed for the agent (companion_app) until it acknowledges them.
 */
export interface SessionApplicationEventStatus {
  state: 'idle' | 'pending' | 'queued' | 'delivering' | 'failed';
  /** Committed user edits in pending, queued or delivering batches. */
  undelivered: number;
  /** Retained failed batches awaiting acknowledgement. */
  failed: number;
  /** Bounded human-readable reason for the newest failure or admission refusal. */
  failure?: string;
}

/**
 * The application attached to an AgentSession snapshot/patch as
 * `AgentSession.application`. Absence means the session shows trusted HTML chat.
 *
 * Patches replace the whole session object (clients do not merge fields), so a
 * patch without `application` means the application was removed or is absent.
 */
export interface SessionApplicationDescriptor {
  /** Stable across code replacement; a UUID. */
  id: string;
  /** Library bundle name of the current code. */
  name: string;
  /** Host-assigned code version: 1 on first apply, +1 for each replacement. */
  version: number;
  /** State revision: +1 for each committed state change. */
  revision: number;
  /**
   * Desktop-only capability for the restricted application view, shaped like
   * a widget view URL (`http://127.0.0.1:<port>/view/<64 hex>`). It stays the
   * same across code replacement. Removed from remote/phone snapshots. Absent
   * when the application is unavailable (see `error`).
   */
  viewUrl?: string;
  /** Readable text description produced by the bundle, 1–4000 characters. */
  text: string;
  eventMode: SessionApplicationEventMode;
  eventStatus?: SessionApplicationEventStatus;
  /**
   * Present when the saved application could not be restored (missing or
   * corrupt bundle, invalid saved state). Its saved data is kept unchanged;
   * the UI keeps trusted chat/history available. Bounded to 500 characters.
   */
  error?: string;
}

/** `GET <viewUrl>/state` response for an application view. */
export interface SessionApplicationStateResponse {
  kind: 'application';
  version: number;
  revision: number;
  /** Current state; `props` repeats it for the shared widget host script. */
  data: Record<string, unknown>;
  props: Record<string, unknown>;
  textScale: number | null;
}

/** `POST <viewUrl>/action` request body from the trusted view host. */
export interface SessionApplicationActionRequest {
  action: string;
  args?: Record<string, unknown>;
  /** Code version the view was loaded with; a mismatch is refused. */
  version: number;
  /** Optional expected state revision; omitted for ordinary targeted actions. */
  revision?: number;
  /** Retry deduplication key generated by the host page, ≤200 characters. */
  requestId: string;
}

/** `POST <viewUrl>/query` request body from the trusted view host. */
export interface SessionApplicationQueryRequest {
  name: string;
  args?: Record<string, unknown>;
  /** Code version the view was loaded with; a mismatch is refused. */
  version: number;
}

/** Shared size and count limits. Documented in README.md. */
export const sessionApplicationLimits = {
  /** Serialized state JSON, as for widget props. */
  stateBytes: 128 * 1024,
  argsBytes: 32 * 1024,
  resultBytes: 16 * 1024,
  queriesPerBundle: 20,
  actionsPerBundle: 20,
  /** Receipts kept for retry deduplication (count and total bytes). */
  receipts: 64,
  receiptBytes: 64 * 1024,
  /** Edits detailed per event batch; further edits are counted only. */
  detailedEditsPerBatch: 16,
  /** Serialized size of one edit's args/result summary before it is elided. */
  editDetailBytes: 1024,
  /**
   * Failed batches retained until acknowledged. While this many are retained,
   * a user edit that needs a new batch is refused before any state change.
   */
  failedBatches: 4,
  /** Default debounce before an immediate-mode batch is queued. */
  immediateDebounceMilliseconds: 1500,
} as const;
